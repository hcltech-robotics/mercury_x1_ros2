#!/usr/bin/env python3
"""Arm link hull points for the arm-aware Nav2 footprint (mercury_x1_bringup/scripts/arm_footprint.py).

Reads the per-link GLBs (link frame, see convert_meshes.py) and keeps a few dozen points of each
link's convex hull, written as YAML: {link: [[x, y, z], ...]}.

  uv run --with trimesh --with scipy tools/arm_hulls.py meshes ../../bringup/mercury_x1_bringup/config/arm_hulls.yaml
"""
import json
import os
import sys

import numpy as np
import trimesh


def hull_points(mesh: trimesh.Trimesh, n: int) -> np.ndarray:
    v = mesh.convex_hull.vertices
    if len(v) <= n:
        return v
    # farthest-point sampling keeps the extremes (what matters for a 2D outline)
    keep = [int(np.argmax(np.linalg.norm(v - v.mean(0), axis=1)))]
    d = np.linalg.norm(v - v[keep[0]], axis=1)
    while len(keep) < n:
        keep.append(int(np.argmax(d)))
        d = np.minimum(d, np.linalg.norm(v - v[keep[-1]], axis=1))
    return v[keep]


def main(mesh_dir: str, out: str, n: int = 32) -> None:
    with open(os.path.join(mesh_dir, "index.json")) as f:
        index = json.load(f)
    lines = ["# generated by mercury_x1_web/tools/arm_hulls.py from the URDF visuals (link frames, metres)"]
    for link in sorted(k for k in index if k.startswith("link") and k[4:5].isdigit()):
        files = index[link].get("files") or [index[link]["file"]]
        mesh = trimesh.util.concatenate([trimesh.load(os.path.join(mesh_dir, f), force="mesh") for f in files])
        pts = hull_points(mesh, n)
        lo, hi = mesh.bounds
        print(f"{link}: {len(mesh.vertices)} verts, bounds {lo.round(3)} .. {hi.round(3)}")
        lines.append(f"{link}: [" + ", ".join(f"[{x:.3f}, {y:.3f}, {z:.3f}]" for x, y, z in pts) + "]")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
